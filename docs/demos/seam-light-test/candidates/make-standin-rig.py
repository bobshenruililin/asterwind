"""QA stand-in only, not art: writes candidates/standin-lamp-rig/ to exercise the rig path (a moving lamp head
with coupled light) before Robert's real kit exists. Everything here is cut from or graded from one existing
still, so it shows exactly the failures the real kit must avoid:
  * the 'clean plate' is a crude patch, so the revealed background is wrong;
  * the 'lit passes' are the same baked light pushed around by masks, not relighting;
  * the head is a hand-traced polygon, so its fibre edge and Mara's hair beside it are chewed.
   python3 -I docs/demos/seam-light-test/candidates/make-standin-rig.py"""
import json, pathlib, random
from PIL import Image, ImageChops, ImageDraw, ImageEnhance, ImageFilter
here = pathlib.Path(__file__).resolve().parent
repo = here.parents[3]
out = here / 'standin-lamp-rig'; out.mkdir(parents=True, exist_ok=True)
lit = Image.open(repo / 'film' / 'assets' / 'performanceOffer.webp').convert('RGB')
W, H = lit.size
P = lambda pts: [(x / 100 * W, y / 100 * H) for x, y in pts]
# The shade, traced by hand from the plate (percent of the frame). Pivot: where the head meets the arm's knuckle.
head = P([(30.0, 15.0), (30.4, 12.6), (32.6, 12.3), (33.6, 14.8), (35.0, 16.0), (36.4, 16.6), (36.6, 18.2), (35.2, 18.4),
          (37.5, 22.0), (39.9, 27.4), (39.6, 29.2), (37.5, 31.0), (34.5, 33.0), (31.5, 34.4), (29.8, 34.2), (29.9, 30.5),
          (30.6, 27.5), (30.0, 21.0)])
PIVOT = [36.4, 17.4]
mask = Image.new('L', (W, H), 0); ImageDraw.Draw(mask).polygon(head, fill=255)
soft = mask.filter(ImageFilter.GaussianBlur(1.2))
cut = lit.copy().convert('RGBA'); cut.putalpha(soft)
cut.save(out / 'head.png', optimize=True)
# Night grade (the same cheat as the first stand-in), then a crude 'clean plate': the head's footprint is filled
# from a patch of dark wall, tiled, with a feathered edge.
def night(im):
    n = ImageEnhance.Brightness(ImageEnhance.Color(im).enhance(.5)).enhance(.34)
    ind = Image.new('RGB', im.size, (70, 78, 150))
    return Image.blend(n, ImageChops.multiply(n, ind).point(lambda v: min(255, v * 3)), .35)
N = night(lit)
patch = N.crop((int(.41 * W), int(.02 * H), int(.51 * W), int(.12 * H)))
fill = Image.new('RGB', (W, H))
for y in range(0, H, patch.height):
    for x in range(0, W, patch.width):
        fill.paste(patch, (x, y))
grow = mask.filter(ImageFilter.MaxFilter(9)).filter(ImageFilter.GaussianBlur(6))
clean = Image.composite(fill, N, grow)
clean.save(out / 'N0.webp', quality=86)
# 'Lit passes': the baked lit plate revealed by a pool aimed at the spare, the centre and the original, over the
# clean night plate. Real passes must be relit art; these only move the old light around.
def pool(cx, cy, r):
    m = Image.new('L', (W, H), 0); d = ImageDraw.Draw(m)
    for i in range(40, 0, -1):
        rr = r * i / 40; v = int(255 * (1 - (i / 40) ** 2))
        d.ellipse([cx / 100 * W - rr, cy / 100 * H - rr * .9, cx / 100 * W + rr, cy / 100 * H + rr * .9], fill=v)
    return m.filter(ImageFilter.GaussianBlur(20))
headless = Image.composite(clean, lit, grow)  # the lit room without the old head painted in
for name, (cx, cy) in {'spare': (24, 76), 'centre': (44, 62), 'original': (77, 60)}.items():
    Image.composite(headless, clean, pool(cx, cy, W * .24)).save(out / f'L-{name}.webp', quality=86)
cand = {
    "title": "Stand-in lamp rig (QA, not art): the head turns toward the light; coupled passes crossfade",
    "by": "Opus, generated by candidates/make-standin-rig.py",
    "status": "example",
    "rig": {
        "plate": "performanceOffer",
        "clean": "N0.webp",
        "lightPasses": [{"at": 0, "src": "L-spare.webp"}, {"at": 0.4, "src": "L-centre.webp"}, {"at": 1, "src": "L-original.webp"}],
        "rotate": {"src": "head.png", "pivot": PIVOT, "range": [-12, 46]},
        "aimRange": [24, 77],
        "mask": False,
        "settle": "creak"
    }
}
(out / 'candidate.json').write_text(json.dumps(cand, indent=1) + '\n')
print('wrote', out)
