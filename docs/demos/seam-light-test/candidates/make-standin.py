"""QA stand-in only, not art: writes candidates/standin-example/ so the harness's paths can be exercised before
Robert's real experiments arrive. The 'unlit' plate is a graded copy of an existing still (exactly what a real
relit pair must NOT be: it is the cheat the pair replaces), and the dust loop is procedural.
   python3 docs/demos/seam-light-test/candidates/make-standin.py"""
import json, math, pathlib, random
from PIL import Image, ImageDraw, ImageEnhance, ImageFilter
here = pathlib.Path(__file__).resolve().parent
repo = here.parents[3]
out = here / 'standin-example'; (out / 'dust').mkdir(parents=True, exist_ok=True)
src = Image.open(repo / 'film' / 'assets' / 'performanceOffer.webp').convert('RGB')
night = ImageEnhance.Brightness(ImageEnhance.Color(src).enhance(.5)).enhance(.36)
indigo = Image.new('RGB', src.size, (88, 96, 168))
night = Image.blend(night, Image.composite(indigo, night, Image.new('L', src.size, 40)), .5)
night.save(out / 'performanceOffer-N.webp', quality=86)
# A seamless 4 s loop at 12 fps: each mote fades in, drifts up a little and fades out on its own phase.
W, H, N = 640, 360, 48
rnd = random.Random(5)
motes = [(rnd.random() * W, rnd.random() * H, rnd.random(), 1.1 + rnd.random() * 2.4, 8 + rnd.random() * 22) for _ in range(90)]
for f in range(N):
    t = f / N
    im = Image.new('RGBA', (W * 2, H * 2), (0, 0, 0, 0)); d = ImageDraw.Draw(im)
    for x, y, ph, r, rise in motes:
        u = (t + ph) % 1
        a = math.sin(math.pi * u) ** 2
        cx, cy = x + math.sin(6.283 * (u + ph)) * 4, y - rise * u
        R = r * 2
        d.ellipse([cx * 2 - R, cy * 2 - R, cx * 2 + R, cy * 2 + R], fill=(255, 232, 186, int(235 * a)))
    im.resize((W, H), Image.LANCZOS).filter(ImageFilter.GaussianBlur(.6)).save(out / 'dust' / f'{f:02d}.png', optimize=True)
cand = {
    "title": "Stand-in example (QA, not art): an unlit plate and a dust loop seen only in the light",
    "by": "Opus, generated by candidates/make-standin.py",
    "status": "example",
    "plates": {"performanceOffer": {"unlit": "performanceOffer-N.webp"}},
    "loops": [{"plate": "performanceOffer", "frames": "dust/%02d.png", "count": N, "fps": 12,
               "box": [18, 28, 64, 64], "inLight": True, "blend": "screen", "opacity": 0.85}]
}
(out / 'candidate.json').write_text(json.dumps(cand, indent=1) + '\n')
print('wrote', out)
